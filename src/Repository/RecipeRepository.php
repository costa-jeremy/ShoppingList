class RecipeRepository extends ServiceEntityRepository
{
    public function __construct(ManagerRegistry $registry)
    {
        parent::__construct($registry, Recipe::class);
    }

    /**
     * L'ordre de création est donné par l'id (la recette n'a pas de date de création).
     *
     * @return Recipe[]
     */
    public function findByUserAndName(User $user, ?string $search, string $order = 'DESC'): array
    {
        $qb = $this->createQueryBuilder('r')
            ->andWhere('r.user = :user')
            ->setParameter('user', $user)
            ->orderBy('r.id', $order === 'ASC' ? 'ASC' : 'DESC');

        if ($search) {
            $qb->andWhere('LOWER(r.name) LIKE :search')
                ->setParameter('search', '%' . mb_strtolower(addcslashes($search, '%_')) . '%');
        }

        return $qb->getQuery()->getResult();
    }

